"""
SolarMind Telemetry Quality & Freshness Detection Rule.

Evaluates telemetry continuity, staleness, missing packets, and data quality flags
to prevent false alarms generated by sensor glitches or network outages.
"""

from datetime import datetime, timezone
from typing import List, Optional

from app.fault_engine.base_rule import BaseDetectionRule
from app.fault_engine.schemas import (
    DetectionCategory,
    DiagnosisResult,
    DiagnosticEvidence,
    InspectionRecommendation,
    SeverityLevel,
    TelemetrySnapshot,
)


class TelemetryQualityRule(BaseDetectionRule):
    """Rule 1: Detects missing, stale, zero-filled, or corrupted telemetry feeds."""

    @property
    def rule_id(self) -> str:
        return "RULE_TEL_QUALITY_001"

    @property
    def name(self) -> str:
        return "Telemetry Continuity & Sensor Quality Rule"

    @property
    def category(self) -> DetectionCategory:
        return DetectionCategory.TELEMETRY_QUALITY

    @property
    def priority(self) -> int:
        return 10  # Highest priority: check data validity first

    def evaluate(self, snapshot: TelemetrySnapshot) -> Optional[DiagnosisResult]:
        inputs_used: List[str] = ["timestamp", "data_quality_flag"]
        missing_inputs: List[str] = []
        evidence_list: List[DiagnosticEvidence] = []

        now_utc = datetime.now(timezone.utc)
        snap_time = snapshot.timestamp
        if snap_time.tzinfo is None:
            snap_time = snap_time.replace(tzinfo=timezone.utc)

        # 1. Check Staleness
        age_minutes = (now_utc - snap_time).total_seconds() / 60.0
        is_daylight = (snapshot.solar_elevation_deg is not None and snapshot.solar_elevation_deg > 5.0) or (
            snapshot.poa_irradiance_wm2 is not None and snapshot.poa_irradiance_wm2 > 100.0
        )

        if age_minutes > 120.0 and is_daylight:
            evidence_list.append(
                DiagnosticEvidence(
                    metric_name="telemetry_freshness_age_minutes",
                    observed_value=round(age_minutes, 1),
                    expected_range_or_baseline="< 15.0 minutes during active daylight",
                    unit="minutes",
                    explanation=f"Telemetry feed is {round(age_minutes / 60.0, 1)} hours stale while solar irradiance is expected.",
                    supporting_factors={"solar_elevation_deg": snapshot.solar_elevation_deg, "irradiance_wm2": snapshot.poa_irradiance_wm2},
                )
            )

        # 2. Check Data Quality Flag
        if snapshot.data_quality_flag.upper() in ["SUSPICIOUS", "CORRUPTED", "MISSING_MEASUREMENTS"]:
            evidence_list.append(
                DiagnosticEvidence(
                    metric_name="data_quality_flag",
                    observed_value=snapshot.data_quality_flag,
                    expected_range_or_baseline="VALID",
                    unit=None,
                    explanation=f"Telemetry collector flagged this record as '{snapshot.data_quality_flag}' due to packet anomalies.",
                )
            )

        # 3. Check All Electrical Measurements None (only if no active fault codes/alarms explain the packet)
        has_active_alarms = bool(snapshot.reported_fault_codes) or (
            snapshot.inverter_status and snapshot.inverter_status.upper() in ["FAULT", "ALARM", "ERROR", "TRIPPED"]
        )
        all_null = (
            snapshot.ac_power_kw is None
            and snapshot.dc_power_kw is None
            and snapshot.ac_voltage_v is None
            and snapshot.dc_voltage_v is None
        )
        if all_null and not has_active_alarms and age_minutes > 15.0:
            evidence_list.append(
                DiagnosticEvidence(
                    metric_name="electrical_metrics_completeness",
                    observed_value="All Null",
                    expected_range_or_baseline="Numeric float values",
                    unit=None,
                    explanation="Inverter telemetry record contains no electrical measurements.",
                )
            )

        if not evidence_list:
            return None

        # Build Diagnosis
        confidence = 0.95 if age_minutes > 180.0 or all_null else 0.75
        confidence_meaning = (
            "Mathematical ratio of telemetry freshness and field completeness. Score > 0.90 indicates confirmed telemetry communication dropout."
        )

        return DiagnosisResult(
            diagnosis_id=self.generate_diagnosis_id("DIAG-TEL"),
            category=DetectionCategory.TELEMETRY_QUALITY,
            severity=SeverityLevel.WARNING if age_minutes < 360.0 else SeverityLevel.HIGH,
            probable_cause="Data logger / WiFi dongle communication loss or cloud polling timeout.",
            root_cause_summary="Stale or missing telemetry stream from inverter logger.",
            evidence=evidence_list,
            inputs_used=inputs_used,
            missing_inputs=missing_inputs,
            rule_identifier=self.rule_id,
            score_or_confidence=confidence,
            confidence_meaning=confidence_meaning,
            recommended_next_inspection=InspectionRecommendation(
                title="Verify Data Logger & Internet Connectivity",
                action_steps=[
                    "Check if the inverter WiFi / 4G logger LED is solid green or blinking error.",
                    "Verify local home router connectivity and signal strength at the inverter location.",
                    "Power cycle the data logger dongle by unplugging and reseating it securely.",
                ],
                priority="MEDIUM",
                safety_precautions=["Do not open high-voltage inverter enclosure to inspect logger."],
                tools_required=["Smartphone with SolarMind app or WiFi analyzer"],
            ),
            energy_impact_kwh=None,  # Cannot calculate energy loss when telemetry is missing
            financial_impact_inr=None,
            is_suspicion_only=False,
        )
