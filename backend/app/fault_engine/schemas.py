"""
SolarMind Modular & Explainable Fault Detection Engine Schemas.

Defines domain data types, detection categories, diagnostic evidence structures,
telemetry snapshots, and structured diagnosis results with documented confidence scores.
"""

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class DetectionCategory(str, Enum):
    """Initial fault detection categories for household and commercial on-grid PV systems."""

    LOW_OR_ABSENT_GENERATION = "LOW_OR_ABSENT_GENERATION"
    UNEXPECTED_POWER_REDUCTION = "UNEXPECTED_POWER_REDUCTION"
    ABNORMAL_VOLTAGE_CURRENT = "ABNORMAL_VOLTAGE_CURRENT"
    ABNORMAL_TEMPERATURE = "ABNORMAL_TEMPERATURE"
    TELEMETRY_QUALITY = "TELEMETRY_QUALITY"
    SHADING_OR_SOILING = "SHADING_OR_SOILING"
    INVERTER_FAULT = "INVERTER_FAULT"
    GRID_INTERRUPTION = "GRID_INTERRUPTION"
    UNKNOWN_INSUFFICIENT_EVIDENCE = "UNKNOWN_INSUFFICIENT_EVIDENCE"


class SeverityLevel(str, Enum):
    """Standardized severity classification."""

    INFO = "INFO"
    LOW = "LOW"
    WARNING = "WARNING"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class DiagnosticEvidence(BaseModel):
    """Atomic piece of supporting or contradictory empirical evidence."""

    model_config = ConfigDict(extra="forbid")

    metric_name: str = Field(description="Name of the electrical or environmental measurement (e.g. 'ac_power_kw', 'v_dc_string_1')")
    observed_value: Any = Field(description="The actual telemetry value measured in the field")
    expected_range_or_baseline: Any = Field(description="The healthy baseline value or acceptable operational range")
    unit: Optional[str] = Field(default=None, description="Physical unit of measurement (e.g. 'kW', 'V', '°C', 'W/m²')")
    explanation: str = Field(description="Plain-language explanation of why this observation indicates an anomaly or healthy behavior")
    supporting_factors: Dict[str, Any] = Field(default_factory=dict, description="Contextual parameters considered (e.g. irradiance, sun elevation)")


class InspectionRecommendation(BaseModel):
    """Actionable, safety-aware field inspection procedure."""

    model_config = ConfigDict(extra="forbid")

    title: str = Field(description="Actionable title of recommended inspection")
    action_steps: List[str] = Field(description="Step-by-step physical or diagnostic procedures for technicians/homeowners")
    priority: str = Field(default="MEDIUM", description="Urgency of inspection ('LOW', 'MEDIUM', 'HIGH', 'IMMEDIATE')")
    safety_precautions: List[str] = Field(default_factory=list, description="Mandatory safety warnings (e.g. DC high voltage isolation)")
    tools_required: List[str] = Field(default_factory=list, description="Recommended diagnostic tools (e.g. DC clamp meter, thermal camera, multimeter)")


class TelemetrySnapshot(BaseModel):
    """Complete contextual telemetry snapshot for rule evaluation."""

    model_config = ConfigDict(extra="ignore")

    plant_id: int
    inverter_id: str
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    # DC Measurements
    dc_voltage_v: Optional[float] = None
    dc_current_a: Optional[float] = None
    dc_power_kw: Optional[float] = None
    mppt_channels: List[Dict[str, float]] = Field(default_factory=list)  # e.g. [{"channel": 1, "v": 320.0, "i": 7.5}]
    mppt_count: int = 1
    strings_count: int = 1

    # AC Measurements
    ac_voltage_v: Optional[float] = None
    ac_current_a: Optional[float] = None
    ac_power_kw: Optional[float] = None
    grid_frequency_hz: Optional[float] = None

    # Environmental & Thermal
    internal_temp_c: Optional[float] = None
    ambient_temp_c: Optional[float] = None
    module_temp_c: Optional[float] = None
    poa_irradiance_wm2: Optional[float] = None
    solar_elevation_deg: Optional[float] = None

    # Yield & Hardware Spec
    daily_yield_kwh: Optional[float] = None
    installed_capacity_kwp: float = 5.0
    tariff_rate_inr: float = 7.50
    expected_power_kw: Optional[float] = None

    # Inverter Metadata & Codes
    inverter_manufacturer: Optional[str] = None  # e.g. 'Deye', 'SMA', 'Fronius', 'Growatt'
    inverter_model: Optional[str] = None
    inverter_status: Optional[str] = None
    reported_fault_codes: List[str] = Field(default_factory=list)
    data_quality_flag: str = "VALID"

    # Timeseries context for rate-of-change, degradation, and staleness
    historical_readings: List[Dict[str, Any]] = Field(default_factory=list)
    recent_weather_observations: Optional[Dict[str, Any]] = None


class DiagnosisResult(BaseModel):
    """Complete explainable diagnosis generated by a detection rule."""

    model_config = ConfigDict(extra="forbid")

    diagnosis_id: str = Field(description="Unique deterministic or random diagnosis identifier")
    category: DetectionCategory = Field(description="Core detection category")
    severity: SeverityLevel = Field(description="Standardized severity level")
    probable_cause: str = Field(description="Detailed technical hypothesis of the root cause")
    root_cause_summary: str = Field(description="Executive concise summary")
    evidence: List[DiagnosticEvidence] = Field(description="List of empirical observed vs expected evidence points")
    inputs_used: List[str] = Field(description="List of telemetry and environmental telemetry metrics actively evaluated")
    missing_inputs: List[str] = Field(description="List of telemetry metrics that would improve certainty but were absent")
    rule_identifier: str = Field(description="Unique identifier of the rule that produced this diagnosis (e.g. 'RULE_VI_001')")
    score_or_confidence: float = Field(ge=0.0, le=1.0, description="Confidence score between 0.0 (unconfirmed) and 1.0 (certain)")
    confidence_meaning: str = Field(description="Explicit explanation of what the score represents mathematically and diagnostically")
    recommended_next_inspection: InspectionRecommendation = Field(description="Tailored on-site inspection protocol")
    energy_impact_kwh: Optional[float] = Field(default=None, description="Calculated energy deficit in kWh when reliable baseline is available")
    financial_impact_inr: Optional[float] = Field(default=None, description="Calculated financial loss in local currency (INR)")
    is_suspicion_only: bool = Field(default=False, description="True if evidence is circumstantial or missing key sensor confirmation")
